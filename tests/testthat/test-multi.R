test_that("several recordings are read into one tibble", {
  root <- two_recordings()
  recs <- list_g3_recordings(root)
  expect_s3_class(recs, "tbl_df")
  expect_equal(recs$recording, c("rec_a", "rec_b"))
  gaze <- read_g3_gaze(recs)
  one <- read_g3_gaze(g3_example())
  expect_s3_class(gaze, "tbl_df")
  expect_equal(nrow(gaze), 2 * nrow(one))
  expect_equal(names(gaze)[1], "recording")
  expect_equal(read_g3_gaze(recs$path), gaze)
  expect_setequal(unique(read_g3_imu(recs)$recording), c("rec_a", "rec_b"))
  expect_setequal(unique(read_g3_events(recs)$recording), c("rec_a", "rec_b"))
})

test_that("sync port functions work per recording", {
  root <- two_recordings()
  recs <- list_g3_recordings(root)
  gaze <- read_g3_gaze(recs)
  events <- read_g3_events(recs)
  p <- g3_syncport(events, "out")
  expect_equal(names(p)[1], "recording")
  p1 <- g3_syncport(read_g3_events(g3_example()), "out")
  expect_gt(nrow(p1), 0)
  expect_equal(nrow(p), 2 * nrow(p1))
  expect_equal(p$pulse[p$recording == "rec_b"], p1$pulse)
  tagged <- g3_add_syncport(gaze, events, "out")
  expect_equal(nrow(tagged), nrow(gaze))
  expect_equal(tagged$pulse[tagged$recording == "rec_a"], tagged$pulse[tagged$recording == "rec_b"])
  ep <- g3_epochs(gaze, events, before = 0.5, after = 2, direction = "out")
  ep1 <- g3_epochs(read_g3_gaze(g3_example()), read_g3_events(g3_example()), before = 0.5,
                   after = 2, direction = "out")
  expect_equal(nrow(ep), 2 * nrow(ep1))
  long <- g3_pupil_long(ep)
  expect_true(all(c("recording", "epoch", "pulse", "epoch_time", "eye", "pupil") %in% names(long)))
})

test_that("duplicate folder names fall back to full paths", {
  a <- two_recordings()
  b <- two_recordings()
  gaze <- read_g3_gaze(c(file.path(a, "rec_a"), file.path(b, "rec_a")))
  expect_equal(length(unique(gaze$recording)), 2)
  expect_true(all(grepl("rec_a$", gaze$recording)))
})

test_that("plots facet by recording", {
  root <- two_recordings()
  recs <- list_g3_recordings(root)
  gaze <- read_g3_gaze(recs)
  p <- plot_g3_pupil(gaze, read_g3_events(recs))
  expect_s3_class(p$facet, "FacetWrap")
  expect_s3_class(plot_g3_gaze(gaze)$facet, "FacetWrap")
  expect_s3_class(plot_g3_pupil(read_g3(g3_example()))$facet, "FacetNull")
})

test_that("read_g3 refuses several paths and data frames need a path column", {
  expect_error(read_g3(c("a", "b")), "one recording")
  expect_error(read_g3_gaze(data.frame(x = 1)), "path")
})
